import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { createHash } from 'node:crypto';
import * as store from '../src/v2-store.mjs';
import { updateWorkingV2 } from '../src/v2-working.mjs';

test('T5 folder inventory, deterministic hashed views, rebuild and conflict preservation', t => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'm5-folders-'));
  t.after(() => fs.rmSync(root, { recursive: true, force: true }));
  const project = store.initializeV2(root);
  store.saveV2(project, { kind: 'methods', title: 'Root method', content: 'root evidence' });
  store.saveV2(project, { kind: 'runs', title: 'Scoped run', content: 'not validated', scope: { path: '01 opt/水 (test)' } });
  updateWorkingV2(project, 'state', 0, { goal: 'Folder task', blockers: ['open diagnostic'] }, { scope: { path: '01 opt/水 (test)' } });
  const folders = store.foldersV2(project).folders;
  assert.deepEqual(folders.map(f => f.path), ['.', '01 opt', '01 opt/水 (test)']);
  assert.equal(folders[2].missing, true);
  assert.equal(folders[2].current, 1);
  assert.equal(folders[2].byKind.runs, 1);
  assert.equal(store.renderFolderViews(project).conflicts.length, 0);
  const hash = createHash('sha256').update('01 opt/水 (test)').digest('hex').slice(0, 12);
  const file = path.join(project.memory, 'folders', `${hash}.md`);
  const initial = fs.readFileSync(file, 'utf8');
  assert.match(initial, /Scoped run/);
  assert.match(initial, /conv=unknown/);
  assert.match(initial, /open diagnostic/);
  assert.match(initial, /knowledge\/runs\//);
  assert.doesNotMatch(initial, /Root method/);
  store.renderFolderViews(project);
  assert.equal(fs.readFileSync(file, 'utf8'), initial);
  fs.rmSync(file);
  fs.writeFileSync(path.join(project.memory, '.internal/index/folders.json'), 'corrupt cache');
  store.renderFolderViews(project);
  assert.equal(fs.readFileSync(file, 'utf8'), initial);
  fs.writeFileSync(file, initial + '\nUSER EDIT');
  assert(store.renderFolderViews(project).conflicts.includes(`folders/${hash}.md`));
  assert.match(fs.readFileSync(file, 'utf8'), /USER EDIT/);
  store.renderFolderViews(project, { force: true });
  assert.equal(fs.readFileSync(file, 'utf8'), initial);
  const index = JSON.parse(fs.readFileSync(path.join(project.memory, '.internal/index/folders.json'), 'utf8'));
  assert.equal(index.schemaVersion, 1);
  assert.equal(index.folders[2].hash, hash);
  assert.equal(store.searchV2(project, 'USER EDIT', { allFolders: true }).hits.length, 0);
});
